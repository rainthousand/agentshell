function goFixture() {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), "agentshell-go-locate-"));
  const root = path.join(base, "workspace");
  const cache = path.join(base, "private-home", "go", "pkg", "mod");
  const externalModule = path.join(cache, "example.org", "sdk@v1.2.3");
  fs.mkdirSync(root, { recursive: true });
  fs.mkdirSync(externalModule, { recursive: true });
  fs.writeFileSync(path.join(root, "go.mod"), "module example.test/app\n\ngo 1.22\n");
  fs.writeFileSync(path.join(root, "client.go"), "package app\n\n type Client struct{}\n");
  fs.writeFileSync(path.join(root, "mock_client.go"), "// Code generated by MockGen. DO NOT EDIT.\npackage app\n");
  fs.writeFileSync(path.join(root, "service_grpc.pb.go"), "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\npackage app\n");
  fs.writeFileSync(path.join(root, "wire_gen.go"), "// Code generated by Wire. DO NOT EDIT.\npackage app\n");
  fs.writeFileSync(path.join(externalModule, "client.go"), "package client\n\nfunc Client() {}\n");
  return { root, cache, externalModule };
}

function fakeRunner(fixture, calls) {
  return async (argv, cwd, options) => {
    calls.push({ argv, cwd, options });
    if (argv[1] === "env") return execution(`${fixture.cache}\n`);
    const local = {
      ImportPath: "example.test/app",
      Dir: fixture.root,
      GoFiles: ["wire_gen.go", "client.go", "service_grpc.pb.go", "mock_client.go"],
      Module: { Path: "example.test/app", Dir: fixture.root, Main: true }
    };
    const dependency = {
      ImportPath: "example.org/sdk/client",
      Dir: fixture.externalModule,
      GoFiles: ["client.go"],
      Module: { Path: "example.org/sdk", Version: "v1.2.3", Dir: fixture.externalModule }
    };
    const values = argv.includes("-deps") ? [dependency, local] : [local];
    return execution(values.map((value) => JSON.stringify(value)).join("\n"));
  };
}

function execution(stdout) {
  return {
    exitCode: 0,
    signal: null,
    durationMs: 1,
    timedOut: false,
    truncated: false,
    stdout,
    stderr: "",
    capturedBytes: Buffer.byteLength(stdout),
    observedBytes: Buffer.byteLength(stdout),
    outputLimitBytes: 4 * 1024 * 1024,
    spawnError: null
  };
}
