export async function loadCommandFamilyModules(command) {
  const modules = await Promise.all(commandFamilySpecifiers(command).map((specifier) => {
    const loader = COMMAND_MODULE_LOADERS[specifier];
    if (!loader) throw new Error(`No command module loader registered for ${specifier}`);
    return loader();
  }));
  return Object.assign({}, ...modules);
}
